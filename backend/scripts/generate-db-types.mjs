// Regenerates types/db.ts — the Kysely table map — from the SQL in src/schemas/sql.
// The SQL stays the source of truth; this file is derived. Run: pnpm db:types
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const DIR = "src/schemas/sql";

const TS_TYPE = (sqlType) => {
  const t = sqlType.toLowerCase();
  if (t.startsWith("numeric") || t.startsWith("decimal")) return "string"; // read via ::text, parsed to bigint
  if (t.startsWith("bigserial") || t.startsWith("bigint") || t.startsWith("int8")) return "string"; // pg returns int8 as string
  if (t.startsWith("smallint") || t.startsWith("integer") || t.startsWith("int")) return "number";
  if (t.startsWith("boolean") || t.startsWith("bool")) return "boolean";
  if (t.startsWith("timestamptz") || t.startsWith("timestamp") || t.startsWith("date"))
    return "Date";
  if (t.startsWith("jsonb") || t.startsWith("json")) return "unknown";
  if (t.endsWith("[]")) return "string[]";
  return "string";
};

const RESERVED = /^(primary|foreign|unique|check|constraint|exclude)\b/i;

const tables = new Map();

for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith(".ts"))
  .sort()) {
  const src = readFileSync(`${DIR}/${file}`, "utf8");
  const re = /CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\n\);/g;
  for (const m of src.matchAll(re)) {
    const [, table, rawBody] = m;
    // strip SQL comments first: they contain commas and would split into phantom columns
    const body = rawBody.replace(/--[^\n]*/g, "");
    const cols = [];
    let depth = 0;
    let buf = "";
    const flush = () => {
      const line = buf.trim();
      buf = "";
      if (!line || RESERVED.test(line)) return;
      const cm = /^([a-z_][a-z0-9_]*)\s+(.+)$/is.exec(line);
      if (!cm) return;
      const name = cm[1];
      const rest = cm[2];
      const typeMatch = /^([a-z]+(?:\s*\([^)]*\))?(?:\[\])?)/i.exec(rest);
      if (!typeMatch) return;
      const sqlType = typeMatch[1];
      const notNull = /\bNOT\s+NULL\b/i.test(rest);
      const isPk = /\bPRIMARY\s+KEY\b/i.test(rest);
      const hasDefault = /\bDEFAULT\b/i.test(rest);
      const serial = /serial/i.test(sqlType);
      let ts = TS_TYPE(sqlType);
      if (!notNull && !isPk) ts = `${ts} | null`;
      const generated = serial || hasDefault;
      cols.push({ name, ts, generated });
    };
    for (const ch of body) {
      if (ch === "(") depth++;
      if (ch === ")") depth--;
      if (ch === "," && depth === 0) {
        flush();
        continue;
      }
      buf += ch;
    }
    flush();
    if (cols.length) tables.set(table, cols);
  }
}

const ifaceName = (table) =>
  `${table
    .split("_")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("")}Table`;

// Columns added after the fact. The engine's schema modules are append-only, so a
// table's shape is its CREATE TABLE plus every ALTER ... ADD COLUMN that follows.
for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith(".ts"))
  .sort()) {
  const src = readFileSync(`${DIR}/${file}`, "utf8").replace(/--[^\n]*/g, "");
  const re =
    /ALTER TABLE\s+(\w+)\s+ADD COLUMN\s+(?:IF NOT EXISTS\s+)?([a-z_][a-z0-9_]*)\s+([\s\S]*?);/gi;
  for (const m of src.matchAll(re)) {
    const [, table, name, rest] = m;
    const cols = tables.get(table);
    if (!cols || cols.some((c) => c.name === name)) continue;
    const typeMatch = /^([a-z]+(?:\s*\([^)]*\))?(?:\[\])?)/i.exec(rest.trim());
    if (!typeMatch) continue;
    const sqlType = typeMatch[1];
    const notNull = /\bNOT\s+NULL\b/i.test(rest);
    const hasDefault = /\bDEFAULT\b/i.test(rest);
    let ts = TS_TYPE(sqlType);
    if (!notNull) ts = `${ts} | null`;
    cols.push({ name, ts, generated: hasDefault });
  }
}

const lines = [
  "// Generated by scripts/generate-db-types.mjs from src/schemas/sql — do not edit.",
  'import type { Generated } from "kysely";',
  "",
];
for (const [table, cols] of [...tables].sort()) {
  lines.push(`export interface ${ifaceName(table)} {`);
  for (const c of cols) {
    lines.push(`  ${c.name}: ${c.generated ? `Generated<${c.ts}>` : c.ts};`);
  }
  lines.push("}", "");
}
lines.push("export interface DB {");
for (const [table] of [...tables].sort()) {
  lines.push(`  ${table}: ${ifaceName(table)};`);
}
lines.push("}", "");

const OUT = "types/ports/db.ts";
const rendered = lines.join("\n");
const columns = [...tables.values()].flat().length;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== rendered) {
    console.error(`${OUT} is out of date with src/schemas/sql. Run \`pnpm db:types\`.`);
    process.exit(1);
  }
  console.log(`${OUT} matches the schema (${tables.size} tables, ${columns} columns)`);
} else {
  writeFileSync(OUT, rendered);
  console.log(`${OUT}: ${tables.size} tables, ${columns} columns`);
}
